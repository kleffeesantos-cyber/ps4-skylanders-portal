#!/usr/bin/env python3
"""Turns web/index.html into source/web.h (a C byte array the plugin serves at '/').

Run from the project root:   python3 tools/gen_web.py
"""
import os
import sys

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = os.path.join(root, "web", "index.html")
dst = os.path.join(root, "source", "web.h")

data = open(src, "rb").read()
if b"\r" in data:
    data = data.replace(b"\r\n", b"\n")

lines = ["/* generated by tools/gen_web.py - do not edit */",
         "static const unsigned char WEB_PAGE[%d] = {" % len(data)]
for i in range(0, len(data), 120):
    lines.append(",".join(str(b) for b in data[i:i + 120]) + ",")
lines.append("};")
open(dst, "w").write("\n".join(lines) + "\n")
print("wrote %s (%d bytes of HTML)" % (dst, len(data)))
